"""Generate artifacts from the model: Structurizr DSL, PlantUML, XHTML autoblocks and manifest.json
into build_dir (workspace.dsl, diagrams/, blocks/, manifest.json)."""
from __future__ import annotations

import hashlib
import json
import re
from datetime import datetime, timezone
from pathlib import Path

from jinja2 import Environment, FileSystemLoader, StrictUndefined

from .model import Model

START = '<ac:structured-macro ac:name="anchor"><ac:parameter ac:name="">docsync:auto:{id}:start</ac:parameter></ac:structured-macro>'
END = '<ac:structured-macro ac:name="anchor"><ac:parameter ac:name="">docsync:auto:{id}:end</ac:parameter></ac:structured-macro>'


def ident(x: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", x)


def autoblock(block_id: str, inner: str, meta: str) -> str:
    """Wraps content into anchors and the "updated automatically" panel (panel title is in Russian - the language of the target space)."""
    return (
        START.format(id=block_id)
        + '<ac:structured-macro ac:name="panel"><ac:parameter ac:name="title">Обновляется автоматически (DocSync)</ac:parameter>'
        + f"<ac:rich-text-body>{inner}<p><sub>{meta}</sub></p></ac:rich-text-body></ac:structured-macro>"
        + END.format(id=block_id)
    )


def placeholder_block(block_id: str) -> str:
    return autoblock(block_id, "<p>Будет заполнено при первой публикации DocSync.</p>", "DocSync: ещё не публиковалось")
def generate_dsl(model: Model) -> dict[str, str]:
    """Returns {'elements.dsl': ..., 'relationships.dsl': ...} - fragments for workspace.dsl."""
    lines = ["// generated by docsync - do not edit by hand"]
    for sys_id, s in model["systems"].items():
        lines.append(f'{ident(sys_id)} = softwareSystem "{s["name"]}" "{s.get("description", "")}" {{')
        for svc_id, svc in model["services"].items():
            if svc.get("system") == sys_id:
                lines.append(f'    {ident(svc_id)} = container "{svc["name"]}" "{svc.get("description", "")}" "{svc.get("technology", "")}"')
                for ds in svc.get("datastores", []) or []:
                    lines.append(f'    {ident(ds["id"])} = container "{ds["id"]}" "Хранилище {svc["name"]}" "{ds.get("technology", "")}" "Database"')
        lines.append("}")
    unassigned = [s for s, v in model["services"].items() if v.get("system") not in model["systems"]]
    if unassigned:
        lines.append('unassigned = softwareSystem "Unassigned" "Сервисы без системы" {')
        for svc_id in unassigned:
            svc = model["services"][svc_id]
            lines.append(f'    {ident(svc_id)} = container "{svc["name"]}" "{svc.get("description", "")}" "{svc.get("technology", "")}"')
        lines.append("}")
    for ext_id, e in model["external"].items():
        tag = "Queue" if e.get("kind") == "queue" else "External"
        lines.append(f'{ident(ext_id)} = softwareSystem "{e["name"]}" "{e.get("description", "")}" "{tag}"')

    def ref(eid: str) -> str:
        if eid in model["services"]:
            sys_id = model["services"][eid].get("system")
            return f'{ident(sys_id) if sys_id in model["systems"] else "unassigned"}.{ident(eid)}'
        return ident(eid)

    rels = ["// generated by docsync - do not edit by hand"]
    for svc_id, svc in model["services"].items():
        for ds in svc.get("datastores", []) or []:
            rels.append(f'{ref(svc_id)} -> {ref(svc_id).rsplit(".", 1)[0]}.{ident(ds["id"])} "читает/пишет" "{ds.get("technology", "")}"')
    for c in model.integrations_for(set(model["services"]) | set(model["external"])):
        tags = [c["protocol"], "async" if c.get("interaction") == "async" else "sync"]
        if c.get("status") == "deprecated":
            tags.append("deprecated")
        ops = ", ".join(c.get("operations", [])[:3])
        rels.append(f'{ref(c["from"])} -> {ref(c["to"])} "{ops or c["protocol"]}" "{c["protocol"]}" "{",".join(tags)}"')
    return {"elements.dsl": "\n".join(lines) + "\n", "relationships.dsl": "\n".join(rels) + "\n"}


def build_workspace(model: Model, fragments: dict[str, str]) -> str:
    """Inlines generated fragments in place of `!include model/generated/<name>.dsl`
    - Kroki and Structurizr Lite receive a single self-contained file."""
    ws = (model.root / "workspace.dsl").read_text(encoding="utf-8")

    def sub(m: re.Match) -> str:
        name = m.group(1)
        return fragments.get(name, f"// {name}: no fragment\n")

    return re.sub(r"^\s*!include\s+model/generated/([\w.-]+)\s*$", sub, ws, flags=re.M)
def generate(model: Model, build_dir: Path, changed: set[str] | None = None, sha: str = "local",
             diagram_mode: str = "attachment", macro_name: str = "plantuml", structurizr=None) -> dict:
    """Generates autoblocks from docs-registry. changed=None - all blocks; otherwise only affected ones."""
    env = Environment(loader=FileSystemLoader(str(model.root / "templates")), undefined=StrictUndefined,
                      autoescape=False, trim_blocks=True, lstrip_blocks=True)
    blocks_dir, diag_dir = build_dir / "blocks", build_dir / "diagrams"
    blocks_dir.mkdir(parents=True, exist_ok=True)
    diag_dir.mkdir(parents=True, exist_ok=True)

    fragments = generate_dsl(model)
    gen_dir = model.model_dir / "generated"
    gen_dir.mkdir(exist_ok=True)
    for name, text in fragments.items():
        (gen_dir / name).write_text(text, encoding="utf-8")
    workspace = build_workspace(model, fragments)
    (build_dir / "workspace.dsl").write_text(workspace, encoding="utf-8")

    registry = model.registry
    manifest = {"generatedAt": datetime.now(timezone.utc).isoformat(), "modelSha": sha, "space": registry.get("space"),
                "c4Mode": "structurizr" if structurizr is not None else "svg", "pages": []}
    # no timestamp here: the block content must be stable for identical model state (idempotent re-publish)
    meta = f"Источник: architecture-model@{sha[:12]}"

    for page in registry["pages"]:
        page_blocks = []
        for b in page["blocks"]:
            elems = model.scope_elements(b["scope"])
            scope_id = b["scope"].partition(":")[2]      # a changed flow/system/integration id matches its own blocks
            if changed is not None and not (changed & (elems | model.neighbours(elems) | {scope_id})):
                continue
            rows = model.integrations_for(elems)
            ctx = {"model": model, "elements": sorted(elems), "rows": rows, "block": b, "scope": b["scope"]}
            diagram = None
            if b["template"] == "c4-view" and structurizr is not None:
                # live diagram from the Structurizr server (workspace is pushed on publish), nothing to render
                diagram = {"name": f'{b["view"]}.embed', "kind": "structurizr-embed", "view": b["view"], "embedded": True}
                inner = structurizr.iframe_macro(b["view"], b["blockId"])
            elif b["template"] == "c4-view":
                diagram = {"name": f'{b["view"]}.svg', "kind": "structurizr", "view": b["view"]}
                inner = _image(diagram["name"])
            elif b["template"] == "sequence":
                puml = env.get_template("sequence.puml.j2").render(**ctx)
                diagram = {"name": f'{b["blockId"]}.svg', "kind": "plantuml"}
                (diag_dir / f'{b["blockId"]}.puml').write_text(puml, encoding="utf-8")
                if diagram_mode == "macro":
                    inner = _macro(macro_name, puml)
                    diagram["embedded"] = True
                else:
                    inner = _image(diagram["name"])
            else:
                inner = env.get_template(f'{b["template"]}.xhtml.j2').render(**ctx)
            xhtml = autoblock(b["blockId"], inner, meta)
            (blocks_dir / f'{b["blockId"]}.xhtml').write_text(xhtml, encoding="utf-8")
            page_blocks.append({"blockId": b["blockId"], "file": f'blocks/{b["blockId"]}.xhtml',
                                "sha256": hashlib.sha256(xhtml.encode()).hexdigest(), "diagram": diagram})
        if page_blocks:
            manifest["pages"].append({"key": page["key"], "pageId": page.get("pageId"), "title": page["title"],
                                      "dryRun": page.get("dryRun", False), "blocks": page_blocks})
    (build_dir / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    return manifest


def _image(filename: str) -> str:
    return f'<p><ac:image ac:width="900"><ri:attachment ri:filename="{filename}"/></ac:image></p>'


def _macro(name: str, source: str) -> str:
    return (f'<ac:structured-macro ac:name="{name}"><ac:plain-text-body><![CDATA[{source}]]></ac:plain-text-body>'
            f"</ac:structured-macro>")
